const translations: Record<AppLanguage, TranslationMap> = { en, tr };

type I18nContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  t: (key: string, params?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  setLanguage: async () => {},
  t: (key) => en[key] || key,
});

const interpolate = (value: string, params?: Record<string, string | number>) => {
  if (!params) return value;
  return Object.entries(params).reduce(
    (text, [key, paramValue]) => text.replace(new RegExp(`{{${key}}}`, "g"), String(paramValue)),
    value
  );
};

export const normalizeLanguage = (value?: string | null): AppLanguage => {
  return value === "tr" ? "tr" : "en";
};

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("en");

  useEffect(() => {
    const loadLanguage = async () => {
      const storedLanguage = normalizeLanguage(await localstorage.get(LANGUAGE_KEY));
      setLanguageState(storedLanguage);
    };

    loadLanguage();
  }, []);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage: async (newLanguage: AppLanguage) => {
      setLanguageState(newLanguage);
      await localstorage.set(LANGUAGE_KEY, newLanguage);
    },
    t: (key: string, params?: Record<string, string | number>) => {
      const value = translations[language][key] || translations.en[key] || key;
      return interpolate(value, params);
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useTranslation = () => useContext(I18nContext);
